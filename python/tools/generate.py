"""Regenerate explicit Python APIs from the Go tool definitions.

Run from any directory: GO=/path/to/go python3 python/tools/generate.py
Use --check in CI to detect contract drift. No runtime Go dependency.
"""
from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[2]
RETURNS = {
    "sess_connect": "ConnectResult", "sess_reconnect": "ConnectResult",
    "sess_exec": "ExecResult", "sess_task_wait": "ExecResult", "sess_task_status": "ExecResult",
    "sess_list": "SessionList", "sess_task_list": "TaskList",
    "sess_configure": "ConfigResult", "sess_get_config": "ConfigResult",
    "sess_get_file": "FileResult", "sess_put_file": "FileResult",
    "sess_tunnel_open": "TunnelResult", "sess_tunnel_close": "TunnelResult",
    "sess_tunnel_list": "list[TunnelResult]", "sess_help": "HelpResult",
}


def annotation(schema):
    if "enum" in schema:
        return "Literal[" + ", ".join(repr(x) for x in schema["enum"]) + "]"
    kind = schema.get("type")
    if isinstance(kind, list):
        return " | ".join(annotation({"type": x}) for x in kind)
    if "anyOf" in schema:
        return " | ".join(annotation(x) for x in schema["anyOf"])
    if kind == "object" and isinstance(schema.get("additionalProperties"), dict):
        return "dict[str, " + annotation(schema["additionalProperties"]) + "]"
    return {"string": "str", "integer": "int", "boolean": "bool",
            "object": "dict[str, Any]", "array": "list[dict[str, Any]]"}.get(kind, "Any")


def generate(tools):
    text = ['# Generated by python/tools/generate.py; edit the generator, not this file.',
            'from __future__ import annotations', '',
            'from typing import Any, Literal', '',
            'from .models import (ConfigResult, ConnectResult, ExecResult, FileResult,',
            '                     HelpResult, ReadResult, Result, SendResult, SessionList,',
            '                     TaskList, TunnelResult)', '', '']
    for asynchronous in (False, True):
        text.append(f'class {"Async" if asynchronous else "Sync"}Methods:')
        text.extend([
            f'    {"async " if asynchronous else ""}def _invoke(self, tool: str, arguments: dict[str, Any]) -> Any:',
            '        raise NotImplementedError', '',
        ])
        for tool in tools:
            name = tool['name']
            props = tool['inputSchema']['properties']
            required = tool['inputSchema'].get('required', [])
            ordered = sorted(props, key=lambda key: (key not in required, key))
            ret = RETURNS.get(name, "ReadResult" if name.startswith('sess_read_') else
                              "SendResult" if name.startswith('sess_send') else "Result")
            text.append(f'    {"async " if asynchronous else ""}def {name}(')
            text.append('        self,' + (' *,' if ordered else ''))
            for key in ordered:
                typ = annotation(props[key])
                if key not in required:
                    typ += ' | None = None'
                text.append(f'        {key}: {typ},')
            text.append(f'    ) -> {ret}:')
            text.append('        ' + repr(tool['description']))
            text.append('        arguments = {')
            text.extend(f'            {key!r}: {key},' for key in ordered)
            text.append('        }')
            text.append(f'        return {"await " if asynchronous else ""}self._invoke({name!r}, arguments)')
            text.append('')
        text.append('')
    return '\n'.join(text).rstrip() + '\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    tools = json.loads(subprocess.check_output(
        [os.environ.get('GO', 'go'), 'run', './python/tools/export.go'], cwd=ROOT))
    path = ROOT / 'python/keepsess/_methods.py'
    source = generate(tools)
    if args.check:
        if path.read_text() != source:
            raise SystemExit('Python API is stale; run python/tools/generate.py')
    else:
        path.write_text(source)
